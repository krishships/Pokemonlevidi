#!/usr/bin/env python3
"""Generate C tables from data/bosses/*.json.

    python3 tools/gen_bosses.py            # write include/generated + src/generated
    python3 tools/gen_bosses.py --check    # fail if the committed output is stale

CI runs --check so the C tables can never drift from the JSON the designers edit.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOSS_DIR = ROOT / "data" / "bosses"
OUT_H = ROOT / "include" / "generated" / "bosses.h"
OUT_C = ROOT / "src" / "generated" / "bosses_data.c"

KINDS = {"melee": "AB_KIND_MELEE", "lunge": "AB_KIND_LUNGE",
         "projectile": "AB_KIND_PROJECTILE", "area": "AB_KIND_AREA"}


def c_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def macro_name(boss_id: str) -> str:
    return "AB_BOSS_" + boss_id.upper().replace("-", "_")


def load_bosses() -> list[dict]:
    files = sorted(BOSS_DIR.glob("*.json"))
    if not files:
        sys.exit(f"no boss files in {BOSS_DIR}")
    bosses = []
    for path in files:
        data = json.loads(path.read_text(encoding="utf-8"))
        data["_file"] = path.name
        bosses.append(data)
    bosses.sort(key=lambda b: b["id"])
    return bosses


def render_h(bosses: list[dict]) -> str:
    lines = [
        "/* AUTO-GENERATED by tools/gen_bosses.py — do not edit by hand.",
        " * Source of truth: the JSON files in data/bosses/",
        " */",
        "#ifndef AB_GENERATED_BOSSES_H",
        "#define AB_GENERATED_BOSSES_H",
        "",
        '#include "action_battle.h"',
        "",
        f"#define AB_BOSS_COUNT {len(bosses)}",
        "",
        "extern const ab_boss_def ab_boss_table[AB_BOSS_COUNT];",
        "",
    ]
    for i, boss in enumerate(bosses):
        lines.append(f"#define {macro_name(boss['id'])} (&ab_boss_table[{i}])")
    lines += [
        "",
        "/* Returns NULL for an unknown id. */",
        "const ab_boss_def *ab_boss_lookup(const char *id);",
        "",
        "#endif /* AB_GENERATED_BOSSES_H */",
        "",
    ]
    return "\n".join(lines)


def render_c(bosses: list[dict]) -> str:
    out = [
        "/* AUTO-GENERATED by tools/gen_bosses.py — do not edit by hand.",
        " * Source of truth: the JSON files in data/bosses/",
        " */",
        '#include "generated/bosses.h"',
        "",
        "#include <string.h>",
        "",
    ]

    for boss in bosses:
        out.append(f"static const ab_attack {boss['id']}_attacks[] = {{")
        for atk in boss["attacks"]:
            out.append(
                "    {{ {id}, {name}, {kind}, {telegraph}, {active}, {recovery}, "
                "{damage}, {poise_damage}, {range_min}, {range_max}, {height}, "
                "{lunge}, {weight}, {min_phase} }},".format(
                    id=c_str(atk["id"]),
                    name=c_str(atk["name"]),
                    kind=KINDS[atk["kind"]],
                    telegraph=atk["telegraph"],
                    active=atk["active"],
                    recovery=atk["recovery"],
                    damage=atk["damage"],
                    poise_damage=atk["poise_damage"],
                    range_min=atk["range_min"],
                    range_max=atk["range_max"],
                    height=atk["height"],
                    lunge=atk["lunge"],
                    weight=atk["weight"],
                    min_phase=atk["min_phase"],
                )
            )
        out.append("};")
        out.append("")

    out.append("const ab_boss_def ab_boss_table[AB_BOSS_COUNT] = {")
    for boss in bosses:
        out.append(
            "    {{ {id}, {name}, {epithet}, {hp}, {poise}, {p2}, {p3}, "
            "{walk}, {aggression}, {count}, {attacks} }},".format(
                id=c_str(boss["id"]),
                name=c_str(boss["name"]),
                epithet=c_str(boss["epithet"]),
                hp=boss["hp"],
                poise=boss["poise"],
                p2=boss["phases"]["phase2_hp_pct"],
                p3=boss["phases"]["phase3_hp_pct"],
                walk=boss["movement"]["walk_speed"],
                aggression=boss["movement"]["aggression"],
                count=len(boss["attacks"]),
                attacks=f"{boss['id']}_attacks",
            )
        )
    out.append("};")
    out.append("")
    out += [
        "const ab_boss_def *ab_boss_lookup(const char *id)",
        "{",
        "    uint8_t i;",
        "",
        "    if (id == NULL)",
        "        return NULL;",
        "    for (i = 0; i < AB_BOSS_COUNT; i++) {",
        "        if (strcmp(ab_boss_table[i].id, id) == 0)",
        "            return &ab_boss_table[i];",
        "    }",
        "    return NULL;",
        "}",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="verify committed output matches the JSON")
    args = parser.parse_args()

    bosses = load_bosses()
    header = render_h(bosses)
    source = render_c(bosses)

    if args.check:
        stale = []
        for path, expected in ((OUT_H, header), (OUT_C, source)):
            actual = path.read_text(encoding="utf-8") if path.exists() else ""
            if actual != expected:
                stale.append(str(path.relative_to(ROOT)))
        if stale:
            print("generated tables are stale: " + ", ".join(stale))
            print("run: python3 tools/gen_bosses.py")
            return 1
        print(f"generated tables up to date ({len(bosses)} bosses)")
        return 0

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_C.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(header, encoding="utf-8")
    OUT_C.write_text(source, encoding="utf-8")
    print(f"wrote {OUT_H.relative_to(ROOT)} and {OUT_C.relative_to(ROOT)} "
          f"({len(bosses)} bosses)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
